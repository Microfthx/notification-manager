type I18nContextValue = {
    locale: Locale;
    setLocale: (locale: Locale) => void;
    toggleLocale: () => void;
    t: (key: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
    const [locale, setLocale] = useState<Locale>(() => {
        const stored = window.localStorage.getItem('notification-manager-locale');
        return stored === 'zh-CN' ? 'zh-CN' : 'en';
    });

    useEffect(() => {
        window.localStorage.setItem('notification-manager-locale', locale);
        document.documentElement.lang = locale === 'zh-CN' ? 'zh-CN' : 'en';
    }, [locale]);

    const value = useMemo<I18nContextValue>(() => {
        const t = (key: string) => messages[locale][key] ?? messages.en[key] ?? key;
        return {
            locale,
            setLocale,
            toggleLocale: () => setLocale((current) => (current === 'en' ? 'zh-CN' : 'en')),
            t,
        };
    }, [locale]);

    return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = () => {
    const context = useContext(I18nContext);
    if (!context) {
        throw new Error('useI18n must be used within I18nProvider');
    }

    return context;
};
